from playwright.sync_api import sync_playwright
errors=[]
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":1200,"height":900})
    pg.on("console", lambda m: errors.append(m.text) if m.type=="error" else None)
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.goto("http://127.0.0.1:8000/"); pg.wait_for_selector(".tile")
    print("tiles:", pg.locator(".tile").count())
    pg.screenshot(path="/tmp/home.png")
    # autocomplete
    pg.fill("#search","vitamin"); pg.wait_for_selector("#suggest a")
    print("suggest:", pg.locator("#suggest a").first.inner_text().replace("\n"," | "))
    pg.screenshot(path="/tmp/suggest.png")
    pg.press("#search","Enter"); pg.wait_for_selector(".card")
    print("search cards:", pg.locator(".card").count())
    pg.locator(".card").first.click(); pg.wait_for_selector(".ing-list")
    print("title:", pg.locator("h1").inner_text(), "| ingredients:", pg.locator(".ing-list li").count())
    print("tags:", pg.locator(".tags .tag").all_inner_texts())
    pg.locator(".ing-list .chip-btn").nth(1).click(); pg.wait_for_selector("#drawer h3")
    print("drawer:", pg.locator("#drawer h3").inner_text(), "|", pg.locator("#drawer").inner_text()[:160].replace("\n"," / "))
    pg.screenshot(path="/tmp/product.png", full_page=True)
    pg.keyboard.press("Escape"); print("drawer hidden:", pg.locator("#drawer").is_hidden())
    print("buy rows:", pg.locator("tbody tr").count())
    pg.goto("http://127.0.0.1:8000/#/category/lipstick"); pg.wait_for_selector("table")
    print("lipstick rows:", pg.locator("tbody tr").count(), "| products:", pg.locator(".card").count())
    pg.screenshot(path="/tmp/category.png", full_page=True)
    pg.goto("http://127.0.0.1:8000/#/ingredients"); pg.wait_for_selector("tbody tr")
    print("ingredients:", pg.locator("tbody tr").count())
    pg.select_option("select","Humectant"); pg.wait_for_timeout(600)
    print("humectants:", pg.locator("tbody tr").count())
    pg.goto("http://127.0.0.1:8000/#/soon/Analyzer"); print("soon:", pg.locator("h1").inner_text())
    pg.set_viewport_size({"width":390,"height":800}); pg.goto("http://127.0.0.1:8000/#/"); pg.wait_for_selector(".tile")
    print("mobile hscroll:", pg.evaluate("document.documentElement.scrollWidth>window.innerWidth"))
    pg.screenshot(path="/tmp/mobile.png")
    b.close()
print("console errors:", errors)
